-- Logins table
CREATE TABLE logins (
  id TEXT PRIMARY KEY NOT NULL, -- UUID
  identity_id TEXT NOT NULL REFERENCES identities (id) ON UPDATE CASCADE ON DELETE CASCADE,
  external_id TEXT NOT NULL,
  source TEXT NOT NULL,
  raw_source_data TEXT, -- JSONB stored as TEXT
  last_login_at TEXT,
  linked_at TEXT NOT NULL
) STRICT;

CREATE UNIQUE INDEX source_external_id_key ON logins (source, external_id);

CREATE INDEX logins_identity_id_idx ON logins (identity_id);

