-- +goose Up
-- Enable foreign key enforcement (SQLite requires this to be set per-connection)
PRAGMA foreign_keys = ON;

-- The main identity table representing users and service accounts
CREATE TABLE identities (
  id TEXT PRIMARY KEY NOT NULL, -- UUID (must be generated by the application)
  first_name TEXT,
  last_name TEXT,
  email TEXT NOT NULL CHECK (email LIKE '%_@__%.__%'),
  type TEXT NOT NULL DEFAULT 'PRIVATE_USER' CHECK (type IN ('PRIVATE_USER', 'SERVICE')),
  description TEXT,
  -- Metadata --
  created_at TEXT NOT NULL, -- Stored as ISO8601 string
  updated_at TEXT,
  disabled_at TEXT
) STRICT;

CREATE INDEX identities_email_idx ON identities (email);

-- SQLite trigger to prevent deletion of the system identity
-- +goose StatementBegin
CREATE TRIGGER prevent_system_identity_deletion BEFORE DELETE ON identities FOR EACH ROW WHEN OLD.id = '00000000-0000-0000-0000-000000000000' BEGIN
SELECT
  RAISE (
    ABORT,
    'Cannot delete the default system identity'
  );
END;
-- +goose StatementEnd

