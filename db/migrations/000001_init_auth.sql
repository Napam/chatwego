-- Session tokens
CREATE TABLE session_tokens (
  hash BLOB PRIMARY KEY, -- BYTEA maps to BLOB
  login_id TEXT NOT NULL REFERENCES logins (id) ON UPDATE CASCADE ON DELETE CASCADE,
  identity_id TEXT NOT NULL REFERENCES identities (id) ON UPDATE CASCADE ON DELETE CASCADE,
  last_used_at TEXT,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT,
  revoked_at TEXT
) STRICT;

CREATE INDEX session_tokens_identity_id_idx ON session_tokens (identity_id);

CREATE INDEX session_tokens_expires_at_idx ON session_tokens (expires_at);

-- Identity roles
CREATE TABLE identity_roles (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  identity_id TEXT NOT NULL REFERENCES identities (id) ON UPDATE CASCADE ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('ADMIN')),
  granted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at TEXT,
  UNIQUE (identity_id, role)
) STRICT;

CREATE INDEX identity_roles_identity_id_idx ON identity_roles (identity_id);


-- +goose Down
DROP TABLE IF EXISTS identity_roles;

DROP TABLE IF EXISTS session_tokens;

DROP TABLE IF EXISTS logins;

DROP TABLE IF EXISTS identities;
